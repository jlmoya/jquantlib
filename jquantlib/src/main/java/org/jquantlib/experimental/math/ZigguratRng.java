    private static final InverseCumulativeNormal INV_CN = new InverseCumulativeNormal();

    private final MersenneTwisterUniformRng mt32_;

    public ZigguratRng() {
        this(0L);
    }

    public ZigguratRng(final long seed) {
        this.mt32_ = new MersenneTwisterUniformRng(seed);
    }

    public Sample< Double > next() {
        return new Sample< Double >(nextGaussian(), 1.0);
    }

    private double nextGaussian() {
        for ( ; ; ) {
            long j = mt32_.nextInt32();   // 32 bits of randomness
            final int f = (int) (j & 1L); // 1 bit picks tail (0/1)
            j >>>= 1;
            final int i = (int) (j & 0x7fL); // 7 bits to choose strip
            j >>>= 7;                          // remaining 24 bits accept/reject
            // Reproduce the C++ semantics:  x = (c[f] * (long)j) * w_[i]
            // where c[f] is -1 / +1. The multiplication runs in signed 32-bit
            // arithmetic, but j < 2^24 so the product fits in signed 32 bits.
            final long signed = (f == 0) ? -((long) j) : j;
            final double x = ((double) signed) * W[i];

            if ( j < K[i] ) {  // accept x
                return x;
            }
            if ( i != 0 ) {  // upper strips
                if ( (F[i - 1] - F[i]) * mt32_.next().value() + F[i] < Math.exp(-0.5 * x * x) ) {
                    return x;
                }
            } else {       // base strip: sample from the tail
                final int sign = (f == 0) ? -1 : 1;
                return sign * INV_CN.op(P * mt32_.next().value() + Q);
            }
        }
    }
