    // ===================== JointStochasticProcess =====================

    /**
     * Minimal concrete JointStochasticProcess matching the probe's
     * TestJointProcess: zero cross-model correlation, state-independent,
     * identity numeraire, trivial pre/postEvolve.
     */
    private static final class TestJointProcess extends JointStochasticProcess {
        TestJointProcess(final List<StochasticProcess> l) {
            super(l);
        }

        @Override
        public void preEvolve(final double t0, final Array x0, final double dt, final Array dw) {
            // no-op
        }

        @Override
        public Array postEvolve(final double t0, final Array x0, final double dt,
                final Array dw, final Array y0) {
            return y0;
        }

        @Override
        public double numeraire(final double t, final Array x) {
            return 1.0;
        }

        @Override
        public boolean correlationIsStateDependent() {
            return false;
        }

        @Override
        public Matrix crossModelCorrelation(final double t0, final Array x0) {
            return new Matrix(size(), size()); // zero matrix
        }
    }

    /**
     * Like {@link TestJointProcess} but with a NON-ZERO off-diagonal cross-model
     * correlation, so the joint covariance is genuinely non-diagonal. This makes
     * the {@code diffusion()}/{@code stdDeviation()} pseudoSqrt path observable:
     * with the C++-default {@code SalvagingAlgorithm.None} (Cholesky) the returned
     * factor is lower-triangular and differs from the Spectral factor.
     */
    private static final class TestCorrelatedJointProcess extends JointStochasticProcess {
        private final double rho;

        TestCorrelatedJointProcess(final List<StochasticProcess> l, final double rho) {
            super(l);
            this.rho = rho;
        }

        @Override
        public void preEvolve(final double t0, final Array x0, final double dt, final Array dw) {
            // no-op
        }

        @Override
        public Array postEvolve(final double t0, final Array x0, final double dt,
                final Array dw, final Array y0) {
            return y0;
        }

        @Override
        public double numeraire(final double t, final Array x) {
            return 1.0;
        }

        @Override
        public boolean correlationIsStateDependent() {
            return false;
        }

        @Override
        public Matrix crossModelCorrelation(final double t0, final Array x0) {
            final Matrix m = new Matrix(size(), size()); // zero, including the diagonal
            m.set(0, 1, rho);
            m.set(1, 0, rho);
            return m;
        }
    }

    /**
     * Cross-validate the {@code diffusion()}/{@code stdDeviation()} matrix-square-root
     * path for a CORRELATED joint process. The covariance is non-diagonal, so the
     * C++-default {@code None} (Cholesky) factor (lower-triangular) is distinct from
     * the {@code Spectral} factor — this is exactly the path that was previously wrong.
     */
    @Test
    public void jointStochasticProcess_twoGbm_correlated() {
        final ReferenceReader r = ref();
        final Case c = r.getCase("joint_two_gbm_correlated");
        final JSONObject in = c.inputs();
        final JSONObject exp = (JSONObject) c.expectedRaw();

        final double rho = in.getDouble("rho");
        final double t   = in.getDouble("t");
        final double t0  = in.getDouble("t0");
        final double dt  = in.getDouble("dt");
        final JSONArray xa = in.getJSONArray("x");
        final Array x = new Array(new double[] { xa.getDouble(0), xa.getDouble(1) });

        final List<StochasticProcess> l = new ArrayList<>();
        l.add(new GeometricBrownianMotionProcess(100.0, 0.05, 0.20));
        l.add(new GeometricBrownianMotionProcess(50.0, 0.03, 0.30));
        final TestCorrelatedJointProcess jp = new TestCorrelatedJointProcess(l, rho);

        assertEquals("jpc.size",    exp.getInt("size"),    jp.size());
        assertEquals("jpc.factors", exp.getInt("factors"), jp.factors());

        final Array x0 = new Array(new double[] { 100.0, 50.0 });

        // covariance must be genuinely non-diagonal here.
        assertMatrix2x2Tight("jpc.covariance", exp.getJSONArray("covariance"), jp.covariance(t0, x0, dt));
        assertMatrix2x2Tight("jpc.crossModelCorrelation",
                exp.getJSONArray("crossModelCorrelation"), jp.crossModelCorrelation(t0, x0));

        // the two matrix-square-root methods under test:
        final Matrix diffusion = jp.diffusion(t, x);
        final Matrix stdDev = jp.stdDeviation(t0, x0, dt);
        assertMatrix2x2Tight("jpc.diffusion", exp.getJSONArray("diffusion"), diffusion);
        assertMatrix2x2Tight("jpc.stdDeviation", exp.getJSONArray("stdDeviation"), stdDev);

        // sanity: the C++-default None (Cholesky) factor is lower-triangular —
        // the upper-right entry is exactly zero (Spectral would be non-zero).
        assertEquals("jpc.diffusion upper-right must be 0 (Cholesky/None signature)",
                0.0, diffusion.get(0, 1), 0.0);
        assertEquals("jpc.stdDeviation upper-right must be 0 (Cholesky/None signature)",
                0.0, stdDev.get(0, 1), 0.0);
    }

