    // ===================== helpers =====================

    private static void assertArrayTight(final String label, final JSONArray exp, final Array got) {
        assertEquals(label + ".length", exp.length(), got.size());
        for (int i = 0; i < exp.length(); i++) {
            tight(label + "[" + i + "]", exp.getDouble(i), got.get(i));
        }
    }

    /** Expected is a flat row-major [m00,m01,m10,m11] array. */
    private static void assertMatrix2x2Tight(final String label, final JSONArray exp, final Matrix got) {
        assertEquals(label + ".rows", 2, got.rows());
        assertEquals(label + ".cols", 2, got.columns());
        tight(label + "[0][0]", exp.getDouble(0), got.get(0, 0));
        tight(label + "[0][1]", exp.getDouble(1), got.get(0, 1));
        tight(label + "[1][0]", exp.getDouble(2), got.get(1, 0));
        tight(label + "[1][1]", exp.getDouble(3), got.get(1, 1));
    }
