    // ===================== EndEulerDiscretization =====================

    @Test
    public void endEulerDiscretization_matchesCpp() {
        final ReferenceReader r = ref();

        // Case 1: GBM, END vs START agree because coefficients are x-only.
        {
            final Case c = r.getCase("endeuler_gbm");
            final JSONObject in = c.inputs();
            final JSONObject exp = (JSONObject) c.expectedRaw();
            final double t0 = in.getDouble("t0"), x0 = in.getDouble("x0"), dt = in.getDouble("dt");

            final GeometricBrownianMotionProcess gbm =
                    new GeometricBrownianMotionProcess(100.0, 0.07, 0.20);
            final EulerDiscretization euler = new EulerDiscretization();
            final EndEulerDiscretization endEuler = new EndEulerDiscretization();

            tight("euler_drift",    exp.getDouble("euler_drift"),    euler.driftDiscretization(gbm, t0, x0, dt));
            tight("euler_diff",     exp.getDouble("euler_diff"),     euler.diffusionDiscretization(gbm, t0, x0, dt));
            tight("euler_var",      exp.getDouble("euler_var"),      euler.varianceDiscretization(gbm, t0, x0, dt));
            tight("endeuler_drift", exp.getDouble("endeuler_drift"), endEuler.driftDiscretization(gbm, t0, x0, dt));
            tight("endeuler_diff",  exp.getDouble("endeuler_diff"),  endEuler.diffusionDiscretization(gbm, t0, x0, dt));
            tight("endeuler_var",   exp.getDouble("endeuler_var"),   endEuler.varianceDiscretization(gbm, t0, x0, dt));
        }

        // Case 2: the discriminating identity — EndEuler evaluates the process
        // at the END point t0+dt: endeuler.drift == proc.drift(t0+dt,x0)*dt, etc.
        {
            final Case c = r.getCase("endeuler_identity");
            final JSONObject in = c.inputs();
            final JSONObject exp = (JSONObject) c.expectedRaw();
            final double t0 = in.getDouble("t0"), x0 = in.getDouble("x0"), dt = in.getDouble("dt");

            final GeometricBrownianMotionProcess gbm =
                    new GeometricBrownianMotionProcess(100.0, 0.07, 0.20);
            final EndEulerDiscretization endEuler = new EndEulerDiscretization();

            // raw process coefficients at END point
            tight("proc_drift_end", exp.getDouble("proc_drift_end"), gbm.drift(t0 + dt, x0));
            tight("proc_diff_end",  exp.getDouble("proc_diff_end"),  gbm.diffusion(t0 + dt, x0));
            // EndEuler discretized values
            tight("endeuler_drift2", exp.getDouble("endeuler_drift"), endEuler.driftDiscretization(gbm, t0, x0, dt));
            tight("endeuler_diff2",  exp.getDouble("endeuler_diff"),  endEuler.diffusionDiscretization(gbm, t0, x0, dt));
            tight("endeuler_var2",   exp.getDouble("endeuler_var"),   endEuler.varianceDiscretization(gbm, t0, x0, dt));

            // and prove the END-point wiring directly in Java
            tight("endeuler_drift_id", gbm.drift(t0 + dt, x0) * dt,
                    endEuler.driftDiscretization(gbm, t0, x0, dt));
        }
    }

