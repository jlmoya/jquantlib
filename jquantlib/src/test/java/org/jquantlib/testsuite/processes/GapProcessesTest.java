    @Test
    public void g2Process_matchesCpp() {
        final ReferenceReader r = ref();
        final Case c = r.getCase("g2");
        final JSONObject in = c.inputs();
        final JSONObject exp = (JSONObject) c.expectedRaw();

        final double a = in.getDouble("a"), sigma = in.getDouble("sigma");
        final double b = in.getDouble("b"), eta = in.getDouble("eta"), rho = in.getDouble("rho");
        final double t = in.getDouble("t"), t0 = in.getDouble("t0"), dt = in.getDouble("dt");
        final JSONArray xa = in.getJSONArray("x");
        final Array x = new Array(new double[] { xa.getDouble(0), xa.getDouble(1) });

        final G2Process g2 = new G2Process(a, sigma, b, eta, rho);

        assertEquals("g2.size", exp.getInt("size"), g2.size());
        tight("g2.x0",    exp.getDouble("x0"),    g2.x0());
        tight("g2.y0",    exp.getDouble("y0"),    g2.y0());
        tight("g2.a",     exp.getDouble("a_acc"),     g2.a());
        tight("g2.sigma", exp.getDouble("sigma_acc"), g2.sigma());
        tight("g2.b",     exp.getDouble("b_acc"),     g2.b());
        tight("g2.eta",   exp.getDouble("eta_acc"),   g2.eta());
        tight("g2.rho",   exp.getDouble("rho_acc"),   g2.rho());

        assertArrayTight("g2.initialValues", exp.getJSONArray("initialValues"), g2.initialValues());
        assertArrayTight("g2.drift", exp.getJSONArray("drift"), g2.drift(t, x));
        assertMatrix2x2Tight("g2.diffusion", exp.getJSONArray("diffusion"), g2.diffusion(t, x));
        assertArrayTight("g2.expectation", exp.getJSONArray("expectation"), g2.expectation(t0, x, dt));
        assertMatrix2x2Tight("g2.stdDeviation", exp.getJSONArray("stdDeviation"), g2.stdDeviation(t0, x, dt));
        assertMatrix2x2Tight("g2.covariance", exp.getJSONArray("covariance"), g2.covariance(t0, x, dt));
    }

